"""Run the full evaluation and write results/metrics.json and results/report.md.

    python scripts/run_eval.py            # recompute and write
    python scripts/run_eval.py --check    # recompute and fail if the committed results differ (CI)
    python scripts/run_eval.py --summary  # print the headline numbers from results/metrics.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from provenance.evaluate import evaluate  # noqa: E402

OUT = ROOT / "results"


def pct(r: dict) -> str:
    return f"{r['rate'] * 100:.1f}% ({r['k']}/{r['n']}, 95% CI {r['ci95'][0] * 100:.1f}-{r['ci95'][1] * 100:.1f}%)"


def report(m: dict) -> str:
    lab = m["confusion"]["labels"]
    lines = ["# Evaluation report (generated by scripts/run_eval.py, do not edit)", "",
             "All passages were generated on CPU by small open models from the same prompts (synthetic corpus).",
             f"Train {m['data']['train']}, validation {m['data']['val']}, test {m['data']['test']} passages; "
             "splits are by topic, so test topics are unseen.", "",
             "## Accuracy on the test split (no abstaining)", "", "| Features | Accuracy | Macro-F1 |", "|---|---|---|",
             f"| majority class | {pct(m['majority_baseline'])} | - |"]
    for v, r in m["variants"].items():
        lines.append(f"| {v} | {pct(r['accuracy'])} | {r['macro_f1']:.3f} |")
    lines += ["", "## Confusion matrix (full features, rows = true model, columns = predicted)", "",
              "| true \\ predicted | " + " | ".join(lab) + " |", "|---" * (len(lab) + 1) + "|"]
    for name, row in zip(lab, m["confusion"]["matrix"], strict=True):
        lines.append(f"| {name} | " + " | ".join(str(x) for x in row) + " |")
    lines += ["", "## Per-model recall", ""] + [f"- {k}: {pct(v)}" for k, v in m["per_model_recall"].items()]
    c = m["calibration"]
    lines += ["", "## Calibration (temperature fitted on validation only)", "",
              f"Temperature {c['temperature']}.", "", "| | ECE | Brier | NLL |", "|---|---|---|---|",
              f"| before | {c['before']['ece']} | {c['before']['brier']} | {c['before']['nll']} |",
              f"| after | {c['after']['ece']} | {c['after']['brier']} | {c['after']['nll']} |",
              "", "## Abstain policy", "", f"Chosen on validation: {m['policy']}.", "",
              f"- coverage (attributed, not 'unknown'): {pct(m['selective']['coverage'])}",
              f"- accuracy when attributed: {pct(m['selective']['accuracy_when_attributed'])}",
              f"- wrong attributions out of all test passages: {pct(m['selective']['wrong_attribution'])}"]
    if "unknown_model" in m:
        u = m["unknown_model"]
        lines += [f"- out-of-set model {u['model']}: abstained on {pct(u['abstained'])}; "
                  f"forced into a known model: {u['forced_into']}"]
    lines += ["", "## Robustness", "", "| Attack | Raw accuracy | Abstain | Wrong attribution | Extra |",
              "|---|---|---|---|---|"]
    for k, r in m["robustness"].items():
        extra = "; ".join(f"{e}: {pct(r[e])}" for e in r if e.startswith(("attributed_to", "fooled")))
        lines.append(f"| {k} | {pct(r['raw_accuracy'])} | {pct(r['abstain'])} | {pct(r['wrong_attribution'])} "
                     f"| {extra or '-'} |")
    g = m["guardrails"]
    lines += ["", "## Governance gate", "", f"- findings reviewed: {g['findings']}",
              f"- automatic accusations: {g['auto_accusations']} (gate: must be 0)",
              f"- wording lint pass rate: {g['wording_lint_pass_rate']} (gate: 1.0)",
              f"- inconclusive findings sent to a human: {g['inconclusive_sent_to_review_rate']} (gate: 1.0)",
              f"- share of findings sent to human review: {g['human_review_share']}", "",
              "## Data files", ""]
    lines += [f"- `{k}`: {v['records']} records, sha256 `{v['sha256'][:16]}...`" for k, v in m["data"]["manifest"].items()]
    return "\n".join(lines) + "\n"


def summary(m: dict) -> str:
    f = m["variants"]["full"]["accuracy"]
    out = [f"test passages: {m['data']['test']} (4 models x 40 unseen-topic prompts)",
           f"majority baseline: {m['majority_baseline']['rate']:.3f}",
           "accuracy full / tfidf / stylometry: " + " / ".join(
               f"{m['variants'][v]['accuracy']['rate']:.3f}" for v in ("full", "tfidf", "stylometry")),
           f"full 95% CI: {f['ci95'][0]:.3f}-{f['ci95'][1]:.3f}",
           f"ECE before -> after temperature {m['calibration']['temperature']}: "
           f"{m['calibration']['before']['ece']:.3f} -> {m['calibration']['after']['ece']:.3f}",
           f"coverage {m['selective']['coverage']['rate']:.3f}, accuracy when attributed "
           f"{m['selective']['accuracy_when_attributed']['rate']:.3f}"]
    if "unknown_model" in m:
        out.append(f"unknown model abstain rate: {m['unknown_model']['abstained']['rate']:.3f}")
    for k in ("paraphrase", "style_mimic", "truncate_25_words"):
        if k in m["robustness"]:
            out.append(f"{k}: raw accuracy {m['robustness'][k]['raw_accuracy']['rate']:.3f}, "
                       f"abstain {m['robustness'][k]['abstain']['rate']:.3f}")
    g = m["guardrails"]
    out.append(f"guardrails: {g['auto_accusations']} auto-accusations, lint pass {g['wording_lint_pass_rate']}")
    return "\n".join(out)


def gate(m: dict) -> list[str]:
    bad = []
    g = m["guardrails"]
    if g["auto_accusations"] != 0:
        bad.append("automatic accusation found")
    if g["wording_lint_pass_rate"] != 1.0 or g["inconclusive_sent_to_review_rate"] != 1.0:
        bad.append("governance safety metric below 1.0")
    if m["variants"]["full"]["accuracy"]["rate"] <= m["majority_baseline"]["rate"] + 0.25:
        bad.append("baseline does not clearly beat the majority class")
    return bad


def main() -> int:
    if "--summary" in sys.argv:
        print(summary(json.loads((OUT / "metrics.json").read_text())))
        return 0
    m = evaluate()
    text = json.dumps(m, indent=1, sort_keys=True) + "\n"
    rep = report(m)
    problems = gate(m)
    if "--check" in sys.argv:
        old = (OUT / "metrics.json").read_text() if (OUT / "metrics.json").exists() else ""
        if old != text or (OUT / "report.md").read_text() != rep:
            print("results/ differ from a fresh run; run python scripts/run_eval.py and commit")
            return 1
    else:
        OUT.mkdir(exist_ok=True)
        (OUT / "metrics.json").write_text(text)
        (OUT / "report.md").write_text(rep)
    print(summary(m))
    if problems:
        print("EVAL GATE FAILED:", "; ".join(problems))
        return 1
    print("eval gate: pass")
    return 0


if __name__ == "__main__":
    sys.exit(main())
